#!/usr/bin/env node
// Generate exact-account cleanup SQL and Redis group-key cleanup from
// successful-registration manifests. Execution remains a separate, explicit
// operation on the development host.
import { readFile, writeFile } from "node:fs/promises";

const [database, output, ...manifests] = process.argv.slice(2);
if (!["im_v07_verify", "im"].includes(database) || !output || manifests.length === 0) {
  console.error("Usage: node scripts/cleanup-test-data.mjs <im_v07_verify|im> <output.sql> <manifest.json>...");
  process.exit(2);
}
const expectedPort = database === "im" ? "8198" : "8199";
const names = new Set();
const groups = new Set();
for (const path of manifests) {
  const manifest = JSON.parse(await readFile(path, "utf8"));
  if (!/^[a-f0-9]{8}$/.test(manifest.run_id) || new URL(manifest.base).port !== expectedPort
    || !Array.isArray(manifest.usernames) || !Array.isArray(manifest.group_ids)) {
    throw new Error(`Invalid manifest or database/port mismatch: ${path}`);
  }
  for (const name of manifest.usernames) {
    if (typeof name !== "string" || !new RegExp(`^v7_${manifest.run_id}_[a-z0-9]{1,4}$`).test(name)) {
      throw new Error(`Unexpected account in manifest: ${path}`);
    }
    names.add(name);
  }
  for (const groupID of manifest.group_ids) {
    if (!Number.isSafeInteger(groupID) || groupID <= 0) {
      throw new Error(`Unexpected group id in manifest: ${path}`);
    }
    groups.add(groupID);
  }
}
if (names.size === 0) throw new Error("No registered accounts to clean up");
const values = [...names].sort().map((name) => `0x${Buffer.from(name).toString("hex")}`).join(",");
const table = `\`${database}\`.\`users\``;
const sql = `-- Exact synthetic accounts from ${manifests.length} manifests; no wildcard deletion.\n`
  + `SELECT COUNT(*) AS matching_test_accounts FROM ${table} WHERE username IN (${values});\n`
  + `DELETE FROM ${table} WHERE username IN (${values});\nSELECT ROW_COUNT() AS deleted_test_accounts;\n`;
await writeFile(output, sql, { flag: "wx", mode: 0o600 });

const redisOutput = output.endsWith(".sql")
  ? `${output.slice(0, -4)}.redis.sh`
  : `${output}.redis.sh`;
const prefix = database === "im" ? "im:v12:" : "im:v13-verify:";
const redisDB = database === "im" ? 0 : 1;
const groupList = [...groups].sort((first, second) => first - second)
  .map((groupID) => `'${groupID}'`).join(", ");
const lua = `local prefix = '${prefix}'
local groups = {${groupList}}
local removed = 0
for _, group in ipairs(groups) do
  local inbox = redis.call('ZRANGE', prefix .. 'group:' .. group .. ':inbox', 0, -1)
  for _, message in ipairs(inbox) do
    removed = removed + redis.call('DEL', prefix .. 'group-messages:' .. message)
  end
  removed = removed + redis.call('DEL',
    prefix .. 'group:' .. group .. ':members',
    prefix .. 'group:' .. group .. ':read',
    prefix .. 'group:' .. group .. ':inbox',
    prefix .. 'group:' .. group .. ':last_accepted_id',
    prefix .. 'group:' .. group .. ':sync_required',
    prefix .. 'group:' .. group .. ':dissolved')
end
for _, stream in ipairs({'group-read:stream', 'group-messages:stream'}) do
  for _, entry in ipairs(redis.call('XRANGE', prefix .. stream, '-', '+')) do
    local fields = entry[2]
    for index = 1, #fields, 2 do
      if fields[index] == 'group_id' then
        for _, group in ipairs(groups) do
          if fields[index + 1] == group then
            removed = removed + redis.call('XDEL', prefix .. stream, entry[1])
          end
        end
        break
      end
    end
  end
end
return removed
`;
const redisScript = `#!/usr/bin/env bash
# Delete this run's Redis group projection keys (${prefix}, DB ${redisDB}).
# Generated by scripts/cleanup-test-data.mjs; run on the development host.
set -euo pipefail
source /opt/IM-Rebuild/infra-v11/infractl
D exec -i im-v11-redis sh -c 'REDISCLI_AUTH="$(cat /run/secrets/redis-password)" \\
  redis-cli --no-auth-warning -h 127.0.0.1 -p 26379 -n ${redisDB} --eval /dev/stdin' <<'LUA'
${lua}LUA
`;
await writeFile(redisOutput, redisScript, { flag: "wx", mode: 0o700 });
console.log(`Prepared cleanup for ${names.size} exact test accounts and ${groups.size} groups in ${database}: ${output}, ${redisOutput}`);
